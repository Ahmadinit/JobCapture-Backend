const test = require('node:test');
const assert = require('node:assert/strict');
const { parsePostAge, STALE_CUTOFF_DAYS } = require('../src/utils/postAge');

test('Freshness gate: STALE_CUTOFF_DAYS is strictly 3', () => {
  assert.equal(STALE_CUTOFF_DAYS, 3);
});

test('Freshness gate: allows posts <= 3 days old', () => {
  const ref = new Date('2026-10-22T12:00:00Z');

  const h4 = parsePostAge('4h', ref);
  assert.equal(h4.isStale, false);
  assert.equal(h4.ageDays < 1, true);
  assert.notEqual(h4.postedAt, null);

  const d1 = parsePostAge('1d', ref);
  assert.equal(d1.isStale, false);
  assert.equal(d1.ageDays, 1);

  const d2 = parsePostAge('2d', ref);
  assert.equal(d2.isStale, false);
  assert.equal(d2.ageDays, 2);

  const d3 = parsePostAge('3d', ref);
  assert.equal(d3.isStale, false);
  assert.equal(d3.ageDays, 3);
});

test('Freshness gate: rejects posts older than 3 days', () => {
  const ref = new Date('2026-10-22T12:00:00Z');

  const d4 = parsePostAge('4d', ref);
  assert.equal(d4.isStale, true);
  assert.equal(d4.ageDays, 4);

  const w1 = parsePostAge('1w', ref);
  assert.equal(w1.isStale, true);
  assert.equal(w1.ageDays, 7);

  const mo1 = parsePostAge('1mo', ref);
  assert.equal(mo1.isStale, true);
  assert.equal(mo1.ageDays, 30);

  const explicitStale = parsePostAge('>3d', ref);
  assert.equal(explicitStale.isStale, true);
});

test('Freshness gate: unknown or null age returns ageDays === null to trigger fail-closed rejection', () => {
  const nullAge = parsePostAge(null);
  assert.equal(nullAge.ageDays, null);

  const emptyAge = parsePostAge('');
  assert.equal(emptyAge.ageDays, null);

  const unparseable = parsePostAge('recently');
  assert.equal(unparseable.ageDays, null);
});

test('Harvester rawText header matches parsePostAge requirements', () => {
  // Simulates the format generated by scripts/harvester.py
  const harvesterSample = 'Posted 1d ago\nSenior Node.js Developer\nAcme Corp | Lahore, Pakistan\nhttps://example.com/job/1\n\nJob description here.';
  const firstLine = harvesterSample.split('\n')[0];
  const ageMatch = firstLine.match(/(\d+d)/i);
  assert.notEqual(ageMatch, null);

  const parsed = parsePostAge(ageMatch[1]);
  assert.equal(parsed.isStale, false);
  assert.equal(parsed.ageDays, 1);
});

test('Cold pitch generation helper logic works correctly with full and minimal job data', () => {
  function generatePitch(job) {
    const leadName = job.posterName || 'Hiring Team';
    const skills = job.skills?.length ? job.skills.slice(0, 3).join(', ') : 'software engineering';
    return `Hi ${leadName},\n\nI saw your post regarding the ${job.jobTitle} position at ${job.company}. With my background in ${skills}, I have built similar systems and would love to contribute to your team.\n\nI've attached my resume and would welcome the chance to connect briefly if you are open to a conversation.\n\nBest regards,`;
  }

  const fullJob = {
    jobTitle: 'Backend Engineer',
    company: 'Fintech Hub',
    posterName: 'Sarah Jenkins',
    skills: ['Node.js', 'PostgreSQL', 'Docker'],
  };
  const fullPitch = generatePitch(fullJob);
  assert.match(fullPitch, /^Hi Sarah Jenkins,/);
  assert.match(fullPitch, /Backend Engineer position at Fintech Hub/);
  assert.match(fullPitch, /Node\.js, PostgreSQL, Docker/);

  const minimalJob = {
    jobTitle: 'Fullstack Dev',
    company: 'Startup',
  };
  const minPitch = generatePitch(minimalJob);
  assert.match(minPitch, /^Hi Hiring Team,/);
  assert.match(minPitch, /software engineering/);
});
